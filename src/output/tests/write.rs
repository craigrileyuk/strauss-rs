#[test]
fn the_files_of_the_project_come_first_with_include_root_autoload() {
    let scratch = scratch_copy("edit-fixture");

    fs::write(
        scratch.path().join("composer.json"),
        r#"{
            "name": "acme/edit-app",
            "autoload": {"files": ["app/helpers.php"], "psr-4": {"App\\": "app/"}},
            "require": {"acme/globals": "*"}
        }"#,
    )
    .unwrap();

    let pipeline = pipeline(scratch.path(), |config| config.include_root_autoload = true);
    let report = pipeline.write(false);

    let autoload = read(&scratch, "vendor-prefixed/autoload.php");
    let root = autoload
        .find("__DIR__ . '/../app/helpers.php',")
        .expect("the project's file");
    let package = autoload
        .find("__DIR__ . '/acme/globals/bootstrap.php',")
        .expect("the package's file");

    assert!(root < package);
    assert_eq!(
        report.warnings,
        ["include_root_autoload: only the `files` of the project's autoload are included"]
    );

    // Without it, the project's files are not in.
    super::pipeline(scratch.path(), |_| {}).write(false);

    assert!(!read(&scratch, "vendor-prefixed/autoload.php").contains("helpers.php"));
}
