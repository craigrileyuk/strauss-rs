#[test]
fn with_the_target_the_vendor_directory_the_files_are_changed_in_place() {
    let (scratch, _, report) = written_fixture(|config| {
        config.target_directory = config.vendor_directory.clone();
    });

    // Only the files that change are written, and no autoloader: it would
    // replace Composer's.
    assert_eq!(report.written, 11);
    assert_eq!(report.modified, 11);
    assert!(report.autoloader.is_empty());
    assert!(!exists(&scratch, "vendor-prefixed"));
    assert!(!exists(&scratch, "vendor/autoload.php"));

    assert!(
        read(&scratch, "vendor/acme/core/src/Client.php").contains("namespace P\\V\\Acme\\Core;")
    );
    assert!(read(&scratch, "vendor/acme/core/src/Client.php").contains(CREDIT));
    assert_eq!(
        read(&scratch, "vendor/acme/core/src/Excluded/Item.php"),
        read(
            &scratch_copy("edit-fixture"),
            "vendor/acme/core/src/Excluded/Item.php"
        )
    );
}

#[test]
fn a_file_that_cannot_be_rewritten_is_copied_as_it_is_with_a_warning() {
    let scratch = scratch_copy("edit-fixture");
    let latin = scratch.path().join("vendor/acme/core/src/Latin.php");

    fs::write(&latin, b"<?php\nnamespace Acme\\Core;\n$s = '\xe9';\n").unwrap();

    let report = pipeline(scratch.path(), |_| {}).write(false);

    assert_eq!(
        fs::read(
            scratch
                .path()
                .join("vendor-prefixed/acme/core/src/Latin.php")
        )
        .unwrap(),
        fs::read(&latin).unwrap()
    );
    assert_eq!(
        report.warnings,
        [
            "acme/core/src/Latin.php was copied as it is: it is not valid UTF-8, so its names could not be updated"
        ]
    );
}

#[cfg(unix)]
#[test]
fn the_mode_of_a_file_is_kept() {
    use std::os::unix::fs::PermissionsExt;

    let scratch = scratch_copy("edit-fixture");

    for file in [
        "vendor/acme/core/src/Client.php",
        "vendor/acme/core/src/Excluded/Item.php",
    ] {
        fs::set_permissions(scratch.path().join(file), fs::Permissions::from_mode(0o755)).unwrap();
    }

    pipeline(scratch.path(), |_| {}).write(false);

    for file in [
        "vendor-prefixed/acme/core/src/Client.php",
        "vendor-prefixed/acme/core/src/Excluded/Item.php",
    ] {
        let mode = fs::metadata(scratch.path().join(file))
            .unwrap()
            .permissions()
            .mode();

        assert_eq!(mode & 0o777, 0o755, "{file}");
    }
}

#[cfg(unix)]
#[test]
fn a_package_that_is_a_link_is_not_changed_in_place() {
    let scratch = scratch_copy("edit-fixture");
    let elsewhere = scratch.path().join("elsewhere");

    fs::create_dir_all(&elsewhere).unwrap();
    fs::rename(
        scratch.path().join("vendor/acme/core"),
        elsewhere.join("core"),
    )
    .unwrap();
    std::os::unix::fs::symlink(
        elsewhere.join("core"),
        scratch.path().join("vendor/acme/core"),
    )
    .unwrap();

    let before = fs::read_to_string(elsewhere.join("core/src/Client.php")).unwrap();

    let report = pipeline(scratch.path(), |config| {
        config.target_directory = config.vendor_directory.clone();
    })
    .write(false);

    assert_eq!(
        fs::read_to_string(elsewhere.join("core/src/Client.php")).unwrap(),
        before
    );
    assert!(
        report.warnings.contains(
            &"acme/core/src/Client.php is not changed: acme/core is a link to another directory"
                .to_string()
        )
    );
    // The rest is still done.
    assert!(read(&scratch, "vendor/acme/consumer/src/Strings.php").contains("namespace P\\V\\"));
}

fn package(name: &str, dependencies: &[&str]) -> Package {
    Package {
        name: name.to_string(),
        version: None,
        package_type: None,
        path: None,
        autoload: Default::default(),
        autoload_overridden: false,
        requires: Vec::new(),
        provides: Vec::new(),
        suggests: Vec::new(),
        license: Vec::new(),
        dependencies: dependencies.iter().map(|name| name.to_string()).collect(),
    }
}

#[test]
fn packages_come_after_what_they_depend_on() {
    let set = PackageSet {
        packages: vec![
            package("a/a", &["b/b", "c/c"]),
            package("b/b", &["c/c"]),
            package("c/c", &[]),
            package("d/d", &[]),
        ],
        ..Default::default()
    };

    assert_eq!(dependency_order(&set), ["c/c", "b/b", "a/a", "d/d"]);
}

#[test]
fn a_dependency_cycle_does_not_loop() {
    let set = PackageSet {
        packages: vec![package("a/a", &["b/b"]), package("b/b", &["a/a"])],
        ..Default::default()
    };

    assert_eq!(dependency_order(&set), ["b/b", "a/a"]);
}

