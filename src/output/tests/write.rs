#[test]
fn the_author_comes_from_composer_json_and_the_date_and_author_can_be_left_out() {
    let scratch = scratch_copy("edit-fixture");

    fs::write(
        scratch.path().join("composer.json"),
        r#"{
            "name": "acme/edit-app",
            "authors": [{"name": "Ada Lovelace"}, {"name": "Someone Else"}],
            "require": {"acme/core": "*", "acme/globals": "*", "acme/consumer": "*", "acme/keep": "*"}
        }"#,
    )
    .unwrap();

    pipeline(scratch.path(), |_| {}).write(false);

    let file = "vendor-prefixed/acme/core/src/Client.php";

    assert!(read(&scratch, file).contains(&format!(
        " * Modified by Ada Lovelace on {DATE} using {CREDIT}."
    )));

    pipeline(scratch.path(), |config| {
        config.include_author = false;
        config.include_modified_date = false;
    })
    .write(false);

    assert!(read(&scratch, file).contains(&format!(" * Modified using {CREDIT}.")));
    assert!(!read(&scratch, file).contains("Ada"));
}

#[test]
fn a_dry_run_reports_what_it_would_write_and_writes_nothing() {
    let scratch = scratch_copy("edit-fixture");
    let pipeline = pipeline(scratch.path(), |_| {});

    let dry = pipeline.write(true);

    assert!(!exists(&scratch, "vendor-prefixed"));
    assert_eq!(
        (dry.written, dry.modified, dry.classmap_entries),
        (13, 11, 12)
    );
    assert_eq!(
        dry.autoloader,
        [
            "vendor-prefixed/autoload-classmap.php",
            "vendor-prefixed/autoload.php"
        ]
    );

    let real = pipeline.write(false);

    assert_eq!(
        (real.written, real.modified, real.classmap_entries),
        (dry.written, dry.modified, dry.classmap_entries)
    );
    assert!(exists(&scratch, "vendor-prefixed/autoload.php"));
}

